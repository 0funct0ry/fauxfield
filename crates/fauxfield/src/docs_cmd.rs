//! `fauxfield docs-cli` (hidden): the CLI reference page, generated from the clap tree so it
//! cannot drift (SPEC §10, M16). `cargo xtask cli-docs` writes it to `reference/cli.md`.

use clap::{Command, CommandFactory};

use crate::cli::Cli;

fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

fn flag_name(a: &clap::Arg) -> String {
    let mut parts = vec![];
    if let Some(s) = a.get_short() {
        parts.push(format!("-{s}"));
    }
    if let Some(l) = a.get_long() {
        parts.push(format!("--{l}"));
    }
    if parts.is_empty() {
        format!("<{}>", a.get_id().as_str().to_uppercase())
    } else {
        parts.join(", ")
    }
}

fn walk(cmd: &Command, path: &str, out: &mut String, leaves: &mut Vec<String>) {
    let subs: Vec<&Command> = cmd.get_subcommands().filter(|c| !c.is_hide_set()).collect();
    if !path.is_empty() {
        out.push_str(&format!("## `{path}`\n\n"));
        if let Some(about) = cmd.get_about() {
            out.push_str(&format!("{about}\n\n"));
        }
        let args: Vec<&clap::Arg> = cmd
            .get_arguments()
            .filter(|a| !a.is_hide_set() && !matches!(a.get_id().as_str(), "help" | "version"))
            .collect();
        if !args.is_empty() {
            out.push_str("| Argument | Description |\n|---|---|\n");
            for a in args {
                let help = a.get_help().map(|h| h.to_string()).unwrap_or_default();
                out.push_str(&format!("| `{}` | {} |\n", flag_name(a), cell(&help)));
            }
            out.push('\n');
        }
        if subs.is_empty() {
            leaves.push(path.trim_start_matches("fauxfield ").replace(' ', "."));
        }
    }
    for s in subs {
        let name = if path.is_empty() {
            s.get_name().to_owned()
        } else {
            format!("{path} {}", s.get_name())
        };
        let full = if path.is_empty() {
            format!("fauxfield {name}")
        } else {
            name
        };
        walk(s, &full, out, leaves);
    }
}

/// The whole reference page.
pub fn markdown() -> String {
    let cmd = Cli::command();
    let mut body = String::new();
    let mut leaves = vec![];
    walk(&cmd, "", &mut body, &mut leaves);
    let mut o = String::from(
        "---\ntitle: CLI reference\ndescription: Every fauxfield command and flag, the --json envelope and the exit codes.\n---\n\n<!-- Generated by `cargo xtask cli-docs`; do not edit. -->\n\n",
    );
    o.push_str(
        "Global flags: `-q`/`--quiet` suppresses informational output, `--no-color` (and the `NO_COLOR` environment variable) disables colour, `-w`/`--workspace <PATH>` picks the Workspace (default: the nearest ancestor containing `fauxfield.toml`) and `--json` prints machine output.\n\n",
    );
    o.push_str("## Exit codes\n\n| Code | Meaning |\n|---|---|\n| 0 | Success |\n| 1 | Runtime error |\n| 2 | Usage error |\n| 3 | Validation failed |\n| 4 | Host not running |\n| 5 | Port in use |\n\n");
    o.push_str("## JSON output\n\nWith `--json` a command prints exactly one JSON document on stdout (JSON Lines for `logs --follow` and `run --log-format json`); logs and prompts go to stderr. A success is `{\"schema\": \"fauxfield.<command>/v1\", \"ok\": true, ...}`. A failure is `{\"schema\": \"fauxfield.error/v1\", \"ok\": false, \"code\", \"message\", \"hint\", \"diagnostics\"}`. Additive fields do not change the version; removing or redefining a field does.\n\n");
    o.push_str("Schema ids: ");
    o.push_str(
        &leaves
            .iter()
            .filter(|l| !matches!(l.as_str(), "open" | "completions" | "mcp.scenario" | "run"))
            .map(|l| format!("`fauxfield.{l}/v1`"))
            .collect::<Vec<_>>()
            .join(", "),
    );
    o.push_str("\n\n");
    o.push_str(&body);
    o
}

pub fn docs_cli() -> i32 {
    print!("{}", markdown());
    crate::cli::EXIT_OK
}

#[cfg(test)]
mod tests {
    #[test]
    fn page_lists_commands_flags_and_codes() {
        let m = super::markdown();
        for s in [
            "## `fauxfield agents init`",
            "`--dry-run`",
            "## `fauxfield route add`",
            "`--from-json`",
            "| 4 | Host not running |",
            "fauxfield.server.add/v1",
        ] {
            assert!(m.contains(s), "missing {s}");
        }
        assert!(!m.contains("docs-cli"), "the generator is hidden");
    }
}
